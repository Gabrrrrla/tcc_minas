"""
agents/enforcers/gnb_slicer.py
------------------------------
RAN-side enforcement point. Runs NATIVELY on the lab host, next to the srsRAN
gNB (which runs natively for DPDK), e.g.:

    sudo GNB_TEMPLATE=/home/lab/srsran/gnb.yaml python3 agents/enforcers/gnb_slicer.py

srsRAN Project has no runtime API for the per-slice PRB share: it is read from
the config at start-up (slicing -> sched_cfg -> min/max_prb_policy_ratio). So
this service renders the operator's config with the ratios MINAS decided and
restarts the gNB, ONLY when the ratios actually change. The restart drops the
UEs for some seconds; they re-attach by themselves. That cost is the reason
the RAN enforcement is reported separately in the text.

The template is never modified: the rendered file goes to GNB_CONFIG_OUT and
the restart command must start the gNB from it (scripts/gnb_restart.sh does).

API (port SLICER_PORT, default 8010):
    PUT /slicing {"prb_total": 51, "slices": {"1": 30, "2": null}}
        -> SST 1: min ratio ceil(100*30/51)=59 %, SST 2: min 0 %; max 100 % for both
    GET /slicing        -> ratios in force + config path
    GET /health

Environment:
    GNB_TEMPLATE        operator's gnb.yaml (required)
    GNB_CONFIG_OUT      rendered config      (default /tmp/gnb.minas.yaml)
    GNB_SLICING_PATH    where the slice list lives in the YAML, dotted
                        (default "cell_cfg.slicing"; check against the srsRAN
                        version in the lab — older ones use top-level "slicing")
    GNB_SLICE_SD        SD to write per slice, or empty to omit (default empty)
    GNB_RESTART_CMD     shell command that (re)starts the gNB from GNB_CONFIG_OUT
                        (default: scripts/gnb_restart.sh next to this repo)
    GNB_LOG             gNB stdout log the restart writes to (default /tmp/gnb.stdout)
    GNB_READY_PATTERN   line that means the gNB is up (default "gNB started")
    GNB_READY_TIMEOUT   seconds to wait for it (default 60)
"""

from __future__ import annotations

import math
import os
import subprocess
import threading
import time

import yaml
from flask import Flask, jsonify, request

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))

TEMPLATE = os.getenv("GNB_TEMPLATE", "")
CONFIG_OUT = os.getenv("GNB_CONFIG_OUT", "/tmp/gnb.minas.yaml")
SLICING_PATH = os.getenv("GNB_SLICING_PATH", "cell_cfg.slicing").split(".")
SLICE_SD = os.getenv("GNB_SLICE_SD", "").strip()
RESTART_CMD = os.getenv("GNB_RESTART_CMD", f"bash {REPO}/scripts/gnb_restart.sh")
GNB_LOG = os.getenv("GNB_LOG", "/tmp/gnb.stdout")
READY_PATTERN = os.getenv("GNB_READY_PATTERN", "gNB started")
READY_TIMEOUT = float(os.getenv("GNB_READY_TIMEOUT", "60"))
SLICES = [int(s) for s in os.getenv("GNB_SLICES", "1,2").split(",")]

app = Flask(__name__)
_lock = threading.Lock()          # one restart at a time
_in_force: dict[int, dict] | None = None


def _ratios(prb_total: int, slices: dict) -> dict[int, dict]:
    out = {}
    for sst in SLICES:
        prb = slices.get(str(sst), slices.get(sst))
        lo = 0 if not prb else min(100, math.ceil(100 * int(prb) / prb_total))
        out[sst] = {"min_prb_policy_ratio": lo, "max_prb_policy_ratio": 100}
    return out


def _render(ratios: dict[int, dict]) -> None:
    with open(TEMPLATE, encoding="utf-8") as f:
        cfg = yaml.safe_load(f) or {}
    node = cfg
    for key in SLICING_PATH[:-1]:
        node = node.setdefault(key, {})
    entries = []
    for sst, r in ratios.items():
        e: dict = {"sst": sst}
        if SLICE_SD:
            e["sd"] = int(SLICE_SD, 0)
        e["sched_cfg"] = dict(r)
        entries.append(e)
    node[SLICING_PATH[-1]] = entries
    tmp = CONFIG_OUT + ".tmp"
    with open(tmp, "w", encoding="utf-8") as f:
        f.write("# generated by MINAS gnb_slicer.py from " + TEMPLATE + " -- do not edit\n")
        yaml.safe_dump(cfg, f, sort_keys=False)
    os.replace(tmp, CONFIG_OUT)


def _restart() -> tuple[int, float, bool]:
    """Restart the gNB and wait for READY_PATTERN in its log."""
    t0 = time.monotonic()
    # empty the log first, so only the new gNB's start-up can match the pattern
    open(GNB_LOG, "w").close()
    rc = subprocess.call(RESTART_CMD, shell=True,
                         env={**os.environ, "GNB_CONFIG_OUT": CONFIG_OUT, "GNB_LOG": GNB_LOG})
    if rc != 0:
        return rc, time.monotonic() - t0, False
    while time.monotonic() - t0 < READY_TIMEOUT:
        with open(GNB_LOG, encoding="utf-8", errors="replace") as f:
            if READY_PATTERN in f.read():
                return 0, time.monotonic() - t0, True
        time.sleep(0.5)
    return 0, time.monotonic() - t0, False


@app.get("/health")
def health():
    return jsonify({"status": "ok", "agent": "gnb-slicer", "template": TEMPLATE,
                    "config": CONFIG_OUT, "slicing_path": ".".join(SLICING_PATH)})


@app.get("/slicing")
def get_slicing():
    return jsonify({"in_force": _in_force, "config": CONFIG_OUT})


@app.put("/slicing")
def put_slicing():
    global _in_force
    body = request.get_json(force=True, silent=True) or {}
    prb_total = int(body.get("prb_total") or 0)
    slices = body.get("slices") or {}
    if prb_total <= 0:
        return jsonify({"error": "prb_total must be > 0"}), 400
    ratios = _ratios(prb_total, slices)
    if sum(r["min_prb_policy_ratio"] for r in ratios.values()) > 100:
        return jsonify({"error": "sum of min ratios > 100 %", "ratios": ratios}), 400
    with _lock:
        if ratios == _in_force:
            return jsonify({"changed": False, "ratios": ratios, "restart_s": 0.0})
        try:
            _render(ratios)
        except Exception as e:  # noqa: BLE001 - surfaced to the agent as a failed push
            return jsonify({"error": f"render: {e}"}), 500
        rc, dt, ready = _restart()
        if rc != 0 or not ready:
            _in_force = None  # unknown: force a restart on the next request
            return jsonify({"error": f"gNB restart rc={rc} ready={ready} after {dt:.1f}s",
                            "ratios": ratios}), 502
        _in_force = ratios
    print(f"[gnb-slicer] ratios={ratios} restart={dt:.1f}s", flush=True)
    return jsonify({"changed": True, "ratios": ratios, "restart_s": round(dt, 2)})


def _check_template() -> None:
    """Say at start-up, not mid-experiment, whether the template has the slice
    list where GNB_SLICING_PATH says and which SSTs/SDs it declares: the
    rendered list REPLACES it, so a slice missing from GNB_SLICES (or an SD
    the UEs use) would disappear from the gNB."""
    with open(TEMPLATE, encoding="utf-8") as f:
        cfg = yaml.safe_load(f) or {}
    node = cfg
    for key in SLICING_PATH:
        node = node.get(key) if isinstance(node, dict) else None
    path = ".".join(SLICING_PATH)
    if not isinstance(node, list):
        print(f"[gnb-slicer] WARNING: no slice list at '{path}' in {TEMPLATE}; one will be "
              f"created there. Check the srsRAN version's config reference (older ones use "
              f"top-level 'slicing') and set GNB_SLICING_PATH.", flush=True)
        return
    found = [(e.get("sst"), e.get("sd")) for e in node if isinstance(e, dict)]
    print(f"[gnb-slicer] template slices at '{path}': {found}", flush=True)
    if sorted({s for s, _ in found}) != sorted(SLICES):
        print(f"[gnb-slicer] WARNING: template SSTs {sorted({s for s, _ in found})} != GNB_SLICES "
              f"{SLICES}", flush=True)
    sds = {sd for _, sd in found if sd is not None}
    if sds and not SLICE_SD:
        print(f"[gnb-slicer] WARNING: the template uses SD {sds} but GNB_SLICE_SD is empty; "
              f"the rendered slices would lose it", flush=True)


if __name__ == "__main__":
    if not TEMPLATE or not os.path.exists(TEMPLATE):
        raise SystemExit("set GNB_TEMPLATE to the operator's gnb.yaml")
    _check_template()
    app.run(host="0.0.0.0", port=int(os.getenv("SLICER_PORT", "8010")))
